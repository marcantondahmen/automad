namespace Automad\Ai\Mcp\Transformer;

use Automad\Core\Str;

defined('AUTOMAD') or die('Direct access not permitted!');

/**
 * The transformer class for page IDs. It allows clients to refer to pages by their full URL as well.
 *
 * @author Marc Anton Dahmen
 * @copyright Copyright (c) 2026 by Marc Anton Dahmen - https://marcdahmen.de
 * @license See LICENSE.md for license information
 */
class PageIdTransformer {
	/**
	 * Resolve a page ID from either a page ID or a full page URL like https://domain.com/path/to/page.
	 *
	 * @param string $id
	 * @return string
	 */
	public function fromInput(string $id): string {
		if ($id === '' || str_starts_with($id, '/')) {
			return $id;
		}

		$path = Str::stripStart(strval(parse_url($id, PHP_URL_PATH)), AM_BASE_INDEX);

		return '/' . trim($path, '/');
	}
}
