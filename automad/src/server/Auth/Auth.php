namespace Automad\Auth;

use Automad\Auth\Session\Session;
use Automad\Auth\Token\AccessToken;

defined('AUTOMAD') or die('Direct access not permitted!');

/**
 * The Auth utility class.
 *
 * @author Marc Anton Dahmen
 * @copyright Copyright (c) 2026 by Marc Anton Dahmen - https://marcdahmen.de
 * @license See LICENSE.md for license information
 */
class Auth {
	/**
	 * Test whether a request is authenticated.
	 *
	 * @return bool
	 */
	public static function isAuthenticated(): bool {
		if (!empty(Session::getUsername())) {
			return true;
		}

		if (AM_MCP_SERVER_ENABLED) {
			return AccessToken::verifyRequest();
		}

		return false;
	}
}
