namespace Automad\System\Setup\Migrations;

defined('AUTOMAD') or die('Direct access not permitted!');

/**
 * The abstract migration. A migration migrates data that was saved by older versions.
 * Note that all migrations are run again after every update, so every migration must be idempotent,
 * meaning that running it on already migrated data must not change anything.
 *
 * @see \Automad\System\Setup\Migration
 * @author Marc Anton Dahmen
 * @copyright Copyright (c) 2026 by Marc Anton Dahmen - https://marcdahmen.de
 * @license See LICENSE.md for license information
 */
abstract class AbstractMigration {
	/**
	 * Get the migration name that is used for logging.
	 *
	 * @return string
	 */
	abstract public function getName(): string;

	/**
	 * Run the migration.
	 */
	abstract public function run(): void;
}
